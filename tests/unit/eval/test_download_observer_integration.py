@pytest.fixture
def listener():
    with socket.socket() as channel:
        channel.bind(("127.0.0.1", 0))
        channel.listen()
        channel.settimeout(10)
        yield channel


@contextmanager
def _connection(listener):
    channel, _address = listener.accept()
    with channel:
        channel.settimeout(10)
        assert channel.recv(1) == b"R", "Child must report readiness before receiving commands"
        yield channel


@pytest.fixture
def owners(run_eval, client, monkeypatch):
    """Record real process owners, with failure-safe cleanup of only our trees."""
    managed_process = run_eval.ManagedProcess
    recorded = []

    def spawn(*args, **kwargs):
        owner = managed_process(*args, **kwargs)
        recorded.append(owner)
        return owner

    monkeypatch.setattr(run_eval, "ManagedProcess", spawn)
    monkeypatch.setattr(client, "ManagedProcess", spawn)
    try:
        yield recorded
    finally:
        for owner in reversed(recorded):
            owner.close()


@contextmanager
def _background_call(call, owners):
    """Bound test coordination; propagate exceptions from the real runner."""
    result = Future()

    def invoke():
        try:
            result.set_result(call())
        except BaseException as exc:
            result.set_exception(exc)

    thread = Thread(target=invoke, daemon=True)
    thread.start()
    try:
        yield result
    finally:
        # Unblock the runner on failure without racing its context-manager close.
        if thread.is_alive():
            for owner in reversed(owners):
                owner.terminate()
        thread.join(timeout=5)
        assert not thread.is_alive(), "Runner did not return after its owned trees were closed"


def _assert_closed(owners):
    assert owners, "The test must exercise real managed processes"
    for owner in owners:
        assert owner._closed, "Production code must close the owner before returning"
        assert owner.process.poll() is not None, "A model or helper process leaked"


@pytest.fixture
def observations(run_eval, client, monkeypatch):
    """Observe the real client without altering protocol or scan timing."""
    pending = Queue()
    history = []

    def start(pid, env):
        observer = client.DownloadObserver(pid, env)
        poll = observer.poll

        def record(now):
            observation = poll(now)
            history.append(observation)
            pending.put(observation)
            return observation

        observer.poll = record
        return observer

    monkeypatch.setattr(run_eval, "DownloadObserver", start)
    return pending, history


def _await_observation(observations, predicate):
    pending, _history = observations
    deadline = time.monotonic() + 10
    while time.monotonic() < deadline:
        observation = pending.get(timeout=max(0.01, deadline - time.monotonic()))
        if predicate(observation):
            return observation
    pytest.fail("The helper did not report the required observation")


def _child_program(source):
    program = textwrap.dedent(source)
    compile(program, "<pytest-generated-child>", "exec")
    return program


def _download_program(listener, incomplete):
    """Keep a real partial file open until pytest acknowledges its observation."""
    return _child_program(f"""
        import socket
        from pathlib import Path

        path = Path({str(incomplete)!r})
        with socket.create_connection({listener.getsockname()!r}, timeout=10) as control:
            control.sendall(b'R')
            assert control.recv(1) == b'S'
            path.parent.mkdir(parents=True, exist_ok=True)
            stream = path.open('wb')
            try:
                stream.write(bytes(range(256)))
                stream.flush()
                control.sendall(b'W')
                while True:
                    command = control.recv(1)
                    if command == b'G':
                        stream.write(bytes(range(256)))
                        stream.flush()
                    elif command == b'C':
                        stream.close()
                        path.replace(path.with_suffix(''))
                    elif command == b'X':
                        break
                    else:
                        raise RuntimeError('Unexpected controller command')
                    control.sendall(command)
            finally:
                stream.close()
        print('download child finished', flush=True)
    """)


@pytest.mark.parametrize("cache_variable", ["HF_HOME", "XDG_CACHE_HOME"])
@pytest.mark.parametrize("complete", [False, True], ids=["stalled", "completed"])
def test_owned_download_completion_and_stall(
    run_eval, owners, observations, listener, isolated_cache, monkeypatch, cache_variable, complete
):
    monkeypatch.delenv("HF_HOME", raising=False)
    monkeypatch.setenv(cache_variable, str(isolated_cache))
    home = isolated_cache / "huggingface" if cache_variable == "XDG_CACHE_HOME" else isolated_cache
    incomplete = home / "hub" / "models--generated--download" / "blobs" / "weights.incomplete"
    program = _download_program(listener, incomplete)
    monkeypatch.setattr(run_eval, "_HF_DOWNLOAD_STALL_TIMEOUT", 4)
    with _background_call(
        lambda: run_eval._run_subprocess([sys.executable, "-c", program], timeout=20), owners
    ) as future, _connection(listener) as control:
        control.sendall(b"S")
        assert control.recv(1) == b"W"
        active = _await_observation(observations, lambda obs: obs.state == "ACTIVE")
        assert active.epoch > 0
        # Progress is generated only after positive ownership, not on a timer.
        control.sendall(b"G")
        assert control.recv(1) == b"G"
        _await_observation(observations, lambda obs: obs.last_progress > active.last_progress)
        if complete:
            control.sendall(b"C")
            assert control.recv(1) == b"C"
            completed = _await_observation(
                observations,
                lambda obs: obs.state == "IDLE" and obs.completed_epoch == active.epoch,
            )
            assert completed.epoch == active.epoch
            control.sendall(b"X")
        result = future.result(timeout=12)
        assert result["timeout"] is False, result
        assert "observation unavailable" not in result["stderr"], result
        assert result["hf_download_stalled"] is not complete, result
        assert result["exit_code"] == (0 if complete else -1), result
        if complete:
            assert incomplete.with_suffix("").read_bytes() == bytes(range(256)) * 2
            assert "download child finished" in result["stdout"]
        else:
            assert "Hugging Face download stalled" in result["stderr"]
        assert len(owners) == 2, "Exactly one CLI and one observer must be spawned"
        _assert_closed(owners)


@pytest.mark.parametrize("cache_variable", ["HF_HOME", "XDG_CACHE_HOME"])
def test_unrelated_real_download_does_not_suspend_execution_timeout(
    run_eval, owners, observations, listener, isolated_cache, monkeypatch, cache_variable
):
    monkeypatch.delenv("HF_HOME", raising=False)
    monkeypatch.setenv(cache_variable, str(isolated_cache))
    home = isolated_cache / "huggingface" if cache_variable == "XDG_CACHE_HOME" else isolated_cache
    incomplete = home / "hub" / "models--generated--unrelated" / "blobs" / "weights.incomplete"
    with run_eval.ManagedProcess(
        [sys.executable, "-c", _download_program(listener, incomplete)],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    ) as sibling, _connection(listener) as control:
        control.sendall(b"S")
        assert control.recv(1) == b"W"
        with _background_call(
            lambda: run_eval._run_subprocess(
                [sys.executable, "-c", "from threading import Event; Event().wait()"], timeout=8
            ), owners
        ) as future:
            first = _await_observation(observations, lambda obs: obs.state == "IDLE")
            control.sendall(b"G")
            assert control.recv(1) == b"G"
            _await_observation(
                observations,
                lambda obs: obs.state == "IDLE" and obs.observed_at > first.observed_at,
            )
            result = future.result(timeout=12)
            assert result["timeout"] is True, result
            assert result["hf_download_stalled"] is False, result
            assert "observation unavailable" not in result["stderr"], result
            assert result["exit_code"] == -1
            assert all(obs.state != "ACTIVE" for obs in observations[1])
            assert sibling.process.poll() is None, "Unrelated downloader must not be killed"
            _assert_closed(owners[1:])
            control.sendall(b"X")
            assert sibling.process.wait(timeout=5) == 0
    assert len(owners) == 3
    _assert_closed(owners)


@pytest.mark.parametrize("failure", ["hang", "exit", "killed"])
def test_real_runner_falls_back_when_external_helper_is_unavailable(
    run_eval, client, owners, observations, listener, isolated_cache, monkeypatch, tmp_path, failure
):
    worker = tmp_path / "unavailable_observer.py"
    worker.write_text(_child_program(f"""
        import os
        import socket
        from threading import Event

        with socket.create_connection({listener.getsockname()!r}, timeout=10) as control:
            control.sendall(b'R')
            assert control.recv(1) == b'G'
            control.sendall(b'A')
            if {failure!r} == 'exit':
                os._exit(19)
            Event().wait()
    """), encoding="utf-8")
    monkeypatch.setattr(client, "OBSERVER_SCRIPT", worker)
    timeout = 8
    started = time.monotonic()
    with _background_call(
        lambda: run_eval._run_subprocess(
            [sys.executable, "-c", "from threading import Event; Event().wait()"], timeout=timeout
        ), owners
    ) as future, _connection(listener) as control:
        _await_observation(observations, lambda obs: obs.state == "UNKNOWN")
        assert len(owners) == 2
        helper = owners[1]
        assert helper.process.stdout is None, "Helper output must not create a drainable pipe"
        assert helper.process.stderr is None
        control.sendall(b"G")
        assert control.recv(1) == b"A"
        if failure == "killed":
            helper.process.kill()
            helper.process.wait(timeout=5)
        result = future.result(timeout=timeout + 6)
        assert result["exit_code"] == -1
        assert result["timeout"] is True
        assert result["hf_download_stalled"] is False
        assert "observation unavailable" in result["stderr"], result
        expected_error = "no completed observation" if failure == "hang" else "process exited"
        assert expected_error in result["stderr"]
        assert timeout - 0.2 <= result["elapsed"] <= timeout + 6, result
        assert time.monotonic() - started < timeout + 6
        assert len(owners) == 2, "Failed observers must not be restarted"
        _assert_closed(owners)


@pytest.mark.parametrize("exit_code", [0, 7])
def test_normal_exit_captures_file_backed_output_without_pipe_deadlock(
    run_eval, owners, isolated_cache, exit_code
):
    payload = bytes(range(256)) * 1024
    program = (
        "import sys; data = bytes(range(256)) * 1024; "
        "sys.stdout.buffer.write(data); sys.stderr.buffer.write(data[::-1]); "
        f"sys.exit({exit_code})"
    )
    with _background_call(
        lambda: run_eval._run_subprocess([sys.executable, "-c", program], timeout=15), owners
    ) as future:
        result = future.result(timeout=20)
        assert result["exit_code"] == exit_code
        assert result["stdout"] == payload.decode("utf-8", errors="replace")
        assert result["stderr"] == payload[::-1].decode("utf-8", errors="replace")
        assert result["timeout"] is False
        assert result["hf_download_stalled"] is False
        assert owners[0].process.stdout is None
        assert owners[0].process.stderr is None
        _assert_closed(owners)


def test_parent_exit_with_grandchild_holding_stdout_returns_and_cleans_tree(
    run_eval, owners, listener, isolated_cache
):
    grandchild = _child_program(f"""
        import os
        import socket
        from threading import Event

        with socket.create_connection({listener.getsockname()!r}, timeout=10) as control:
            control.sendall(b'R')
            assert control.recv(1) == b'P'
            control.sendall(str(os.getpid()).encode() + b'\\n')
            assert control.recv(1) == b'G'
            print('grandchild owns stdout', flush=True)
            control.sendall(b'A')
            Event().wait()
    """)
    parent = _child_program(f"""
        import socket
        import subprocess
        import sys

        subprocess.Popen([sys.executable, '-c', {grandchild!r}])
        with socket.create_connection({listener.getsockname()!r}, timeout=10) as control:
            control.sendall(b'R')
            assert control.recv(1) == b'P'
            control.sendall(b'parent\\n')
            assert control.recv(1) == b'X'
        print('parent finished', flush=True)
    """)
    with _background_call(
        lambda: run_eval._run_subprocess([sys.executable, "-c", parent], timeout=20), owners
    ) as future, _connection(listener) as first, _connection(listener) as second:
        identities = []
        for control in (first, second):
            control.sendall(b"P")
            with control.makefile("rb") as reader:
                identities.append(reader.readline().strip())
        parent_control, child_control = (
            (first, second) if identities[0] == b"parent" else (second, first)
        )
        descendant = psutil.Process(int(next(value for value in identities if value != b"parent")))
        try:
            child_control.sendall(b"G")
            assert child_control.recv(1) == b"A"
            assert descendant.is_running()
            started = time.monotonic()
            parent_control.sendall(b"X")
            result = future.result(timeout=8)
            assert time.monotonic() - started < 8
            assert result["exit_code"] == 0, result
            assert result["timeout"] is False
            assert "parent finished" in result["stdout"]
            assert "grandchild owns stdout" in result["stdout"]
            _assert_closed(owners)
            descendant.wait(timeout=5)
            assert not descendant.is_running()
        finally:
            # Preserve the failure while ensuring a broken containment cannot leak this child.
            if descendant.is_running():
                descendant.kill()
                descendant.wait(timeout=5)
